def test_compare_with_model():
    print("=== EXECUTING MODEL FIDELITY VALIDATION SUITE (13 COLUMNS) ===")
    
    template_path = 'modelo final po.xlsx'
    output_path = 'validacao_modelo_gerado.xlsx'
    
    rows = generate_sample_macro_data()
    build_xlsx_with_template(template_path, output_path, rows)
    
    # 1. Load Reference and Generated Files
    wb_ref = openpyxl.load_workbook(template_path, data_only=False)
    wb_gen = openpyxl.load_workbook(output_path, data_only=False)
    
    # 2. Check Sheet Names
    print("\n1. Validating Sheet Names & Count...")
    print(f"   Reference Sheets: {wb_ref.sheetnames}")
    print(f"   Generated Sheets: {wb_gen.sheetnames}")
    assert wb_gen.sheetnames == wb_ref.sheetnames, f"Sheet names mismatch! Expected {wb_ref.sheetnames}, got {wb_gen.sheetnames}"
    print("   [PASS] Exact sheet names and order match ('Worksheet', 'Listagem de dados ', 'Associação')")
    
    # 3. Check Worksheet Dimensions & Banner (Row 1)
    print("\n2. Validating Title Banner (Row 1)...")
    ws_gen = wb_gen['Worksheet']
    ws_ref = wb_ref['Worksheet']
    
    val_r1_ref = ws_ref.cell(1, 1).value
    val_r1_gen = ws_gen.cell(1, 1).value
    print(f"   Reference Row 1 text: {repr(val_r1_ref)}")
    print(f"   Generated Row 1 text: {repr(val_r1_gen)}")
    assert 'SAEP - Prova Objetiva' in val_r1_gen, f"Banner text missing in Row 1: {val_r1_gen}"
    assert ws_gen.row_dimensions[1].height == ws_ref.row_dimensions[1].height, f"Row 1 height mismatch! Expected {ws_ref.row_dimensions[1].height}, got {ws_gen.row_dimensions[1].height}"
    print(f"   [PASS] Row 1 banner and height ({ws_gen.row_dimensions[1].height}pt) match.")
    
    # 4. Check Headers (Row 2) - Exact 13 columns (A to M)
    print("\n3. Validating 13 Column Headers (Row 2)...")
    expected_headers = [
        'Departamento Regional (DR)',
        'Unidade operacional (Escola)',
        'Curso',
        'Categoria',
        'Modalidade',
        'Turma',
        'Alunos ',
        'Alunos Aptos/Agendados',
        'Alunos Inaptos/Não Agendados',
        'Presentes',
        'Presentes (%)',
        'Ausentes',
        'Ausentes (%)'
    ]
    gen_headers = [ws_gen.cell(2, c).value for c in range(1, 14)]
    print(f"   Generated Headers: {gen_headers}")
    for idx, (exp, gen) in enumerate(zip(expected_headers, gen_headers)):
        assert exp.strip() == gen.strip(), f"Header column {idx+1} mismatch: expected '{exp}', got '{gen}'"
    print("   [PASS] All 13 column headers match exact names and sequence.")
    
    # 5. Check Column Widths
    print("\n4. Validating Column Widths...")
    for c_letter in ['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H', 'I', 'J', 'K', 'L', 'M']:
        w_ref = ws_ref.column_dimensions[c_letter].width
        w_gen = ws_gen.column_dimensions[c_letter].width
        print(f"   Col {c_letter}: width={w_gen} (ref={w_ref})")
        assert w_gen == w_ref, f"Col {c_letter} width mismatch! Expected {w_ref}, got {w_gen}"
    print("   [PASS] All 13 column dimensions are preserved.")
    
    # 6. Check Data Rows (Rows 3, 4, 5)
    print("\n5. Validating Dynamic Data Rows...")
    assert ws_gen.max_row == 6, f"Expected 6 rows (1 banner + 1 header + 3 data + 1 total), got {ws_gen.max_row}"
    r3 = [ws_gen.cell(3, c).value for c in range(1, 14)]
    print(f"   Row 3 Data: {r3}")
    assert r3[0] == 'SENAI-BA'
    assert r3[1] == 'SENAI Alagoinhas'
    assert r3[2] == 'Técnico em Eletromecânica'
    assert r3[3] == 'CHP'
    assert r3[4] == 'Presencial'
    assert r3[5] == 'ELM01'
    assert r3[6] == 35
    assert r3[7] == 30
    assert r3[8] == 5
    assert r3[9] == 25
    assert abs(r3[10] - 0.833) < 0.01
    assert r3[11] == 5
    assert abs(r3[12] - 0.167) < 0.01
    print("   [PASS] Data rows are correctly populated with appropriate types and numeric values.")
    
    # 7. Check Totals Row (Row 6)
    print("\n6. Validating Totals Row & Formulas...")
    r_tot = [ws_gen.cell(6, c).value for c in range(1, 14)]
    print(f"   Totals Row: {r_tot}")
    assert r_tot[0] == 'Total', f"Expected 'Total' in A6, got {r_tot[0]}"
    assert '=SUBTOTAL(109,Tabela1[[Alunos ]])' in r_tot[6]
    assert '=SUBTOTAL(109,Tabela1[Alunos Aptos/Agendados])' in r_tot[7]
    assert '=SUBTOTAL(109,Tabela1[Alunos Inaptos/Não Agendados])' in r_tot[8] or 'SUBTOTAL(109,Tabela1[Alunos Inaptos' in r_tot[8]
    assert '=SUBTOTAL(109,Tabela1[Presentes])' in r_tot[9]
    assert '=SUBTOTAL(101,Tabela1[Presentes (%)])' in r_tot[10]
    assert '=SUBTOTAL(109,Tabela1[Ausentes])' in r_tot[11]
    assert '=SUBTOTAL(101,Tabela1[Ausentes (%)])' in r_tot[12]
    print("   [PASS] Totals row contains exact SUBTOTAL formulas.")
    
    # 8. Check Table1 Object & AutoFilter
    print("\n7. Validating Table1 Range & AutoFilter...")
    tbl = ws_gen.tables['Tabela1']
    print(f"   Table1 ref: {tbl.ref}")
    assert tbl.ref == 'A2:M6', f"Expected Table1 ref to be 'A2:M6', got '{tbl.ref}'"
    assert tbl.totalsRowCount == 1
    assert tbl.headerRowCount == 1
    assert tbl.tableStyleInfo.name == 'TableStyleMedium9'
    print("   [PASS] Table1 range is dynamically updated to 'A2:M6' with TableStyleMedium9.")
    
    # 9. Check Image / Drawing in zip
    print("\n8. Validating Embedded Logo Image...")
    with zipfile.ZipFile(output_path, 'r') as z_out:
        assert 'xl/media/image1.png' in z_out.namelist(), "Image image1.png missing from generated xlsx!"
        assert 'xl/drawings/drawing1.xml' in z_out.namelist(), "Drawing definition missing from generated xlsx!"
        img_size = z_out.getinfo('xl/media/image1.png').file_size
        print(f"   [PASS] Embedded logo image1.png present ({img_size} bytes) with drawing definition.")
        
    print("\n=== ALL MODEL FIDELITY VALIDATION CHECKS PASSED WITH 100% SUCCESS! ===")

if __name__ == '__main__':
    test_compare_with_model()
